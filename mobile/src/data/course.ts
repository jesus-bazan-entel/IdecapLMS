export function getLesson(lessonId: string) {
  for (const unit of COURSE) {
    const lesson = unit.lessons.find((l) => l.id === lessonId);
    if (lesson) return { unit, lesson };
  }
  return null;
}

export function getUnitIndex(unitId: string) {
  return COURSE.findIndex((u) => u.id === unitId);
}

export const ALL_LESSON_IDS = COURSE.flatMap((u) => u.lessons.map((l) => l.id));

